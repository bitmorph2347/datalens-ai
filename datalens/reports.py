"""CSV and printable-HTML exports."""
from __future__ import annotations

import csv
import html
import io
from datetime import date


def to_csv(columns: list[str], rows: list[dict]) -> str:
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(columns)
    for r in rows:
        w.writerow([r.get(c, "") if not isinstance(r.get(c), list) else "|".join(map(str, r.get(c))) for c in columns])
    return buf.getvalue()


def _cell(v) -> str:
    if v is None:
        return ""
    if isinstance(v, float):
        return f"{v:.2f}"
    if isinstance(v, list):
        return ", ".join(map(str, v))
    return str(v)


def render_report(title: str, sections: list[dict]) -> str:
    esc = html.escape
    parts = [f"<h1>{esc(title)}</h1><p class='muted'>Generated by DataLens AI on {date.today().isoformat()} "
             f"- data: Cricsheet (cricsheet.org), IPL ball-by-ball</p>"]
    for s in sections:
        parts.append(f"<h2>{esc(str(s.get('title', '')))}</h2>")
        if s.get("text"):
            parts.append(f"<p>{esc(str(s['text']))}</p>")
        cols = s.get("columns") or []
        if cols:
            head = "".join(f"<th>{esc(c)}</th>" for c in cols)
            body = "".join("<tr>" + "".join(f"<td>{esc(_cell(r.get(c)))}</td>" for c in cols) + "</tr>" for r in s.get("rows", []))
            parts.append(f"<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>")
        for w in s.get("warnings", []):
            parts.append(f"<p class='warn'>Note: {esc(str(w))}</p>")
    css = ("body{font:14px/1.5 system-ui,sans-serif;max-width:900px;margin:2rem auto;padding:0 1rem;color:#1a1a1a}"
           "h1{font-size:1.6rem}h2{font-size:1.1rem;margin-top:1.8rem;border-bottom:1px solid #ddd;padding-bottom:.2rem}"
           "table{border-collapse:collapse;width:100%;font-size:12.5px}th,td{padding:4px 8px;border-bottom:1px solid #eee;text-align:left}"
           "th{background:#f6f6f6}.muted{color:#777}.warn{color:#8a5a00;font-size:12px}@media print{body{margin:0}}")
    return f"<!doctype html><html><head><meta charset='utf-8'><title>{esc(title)}</title><style>{css}</style></head><body>{''.join(parts)}</body></html>"
